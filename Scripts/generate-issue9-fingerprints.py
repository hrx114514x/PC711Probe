#!/usr/bin/env python3
"""Generate exact code fingerprints from the checked-in reporter fixtures."""
import hashlib
import json
from pathlib import Path
import sys

root=Path(__file__).resolve().parents[1]
details=json.loads((root/'Tests/fixtures/Issue9-details-20261018.json').read_text())
init=bytes.fromhex((root/'Tests/fixtures/InitializePCI-580.hex').read_text())
assert hashlib.sha256(init).hexdigest()==details['initialize_pci_sha256']
start=details['details']['optional_symbol_windows']['__ZN16IONVMeController5startEP9IOService']
position=int(details['initialize_pci_address'],16)-int(start['address'],16)
assert bytes.fromhex(start['bytes'])[position:position+len(init)]==init
arrays={'InitializePCI':init}
for item in details['windows']:
    raw=bytes.fromhex(item['bytes'])
    assert hashlib.sha256(raw).hexdigest()==item['sha256']
    name={'provider':'Provider','map':'Map','virtual_address':'Address','mappers':'Mappers'}[item['candidate']]
    arrays[name]=raw[:87 if name=='Mappers' else 59]
for symbol,length,name in [
    ('__ZN16IONVMeController12GetIOMappersEv',39,'GetIOMappers'),
    ('__ZN16IONVMeController21CreateDeviceInterruptEPFvP8OSObjectP22IOInterruptEventSourceiEPFbS1_P28IOFilterInterruptEventSourceEP9IOService',212,'CreateDeviceInterrupt')]:
    item=details['details']['optional_symbol_windows'][symbol]
    raw=bytes.fromhex(item['bytes'])
    assert hashlib.sha256(raw).hexdigest()==item['sha256']
    arrays[name]=raw[:length]
rows=['// Generated by Scripts/generate-issue9-fingerprints.py from reporter-supplied bytes.',
      '// Exact relative instructions only; no guessed offsets or relaxed masks.',
      '#pragma once','#include <stdint.h>','namespace Issue9Fingerprint {']
for name,raw in arrays.items():
    rows += [f'constexpr uint8_t {name}[] {{']
    rows += ['    '+', '.join(f'0x{x:02X}' for x in raw[n:n+16])+',' for n in range(0,len(raw),16)]
    rows += ['};']
rows += ['}']
text='\n'.join(rows)+'\n'
path=root/'Diagnostics/ExactFingerprints.hpp'
if '--check' in sys.argv:
    assert path.read_text()==text,'generated fingerprint header is stale'
    print('Exact fingerprint header matches all supplied code fixtures')
else:
    path.write_text(text,encoding='utf8')
